const uint8_t* PixelartIcons::getBitmap(const PixelartIcon icon)
{
    switch (icon)
    {
        case PixelartIcon::FOLDER:
            return folderBitmap;
        case PixelartIcon::FILE:
            return fileBitmap;
        case PixelartIcon::IMAGE:
            return imageBitmap;
        case PixelartIcon::VIDEO:
            return videoBitmap;
        case PixelartIcon::UP:
            return upBitmap;
        case PixelartIcon::NONE:
        default:
            return nullptr;
    }
}
