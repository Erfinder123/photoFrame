const BitmapGlyph* BitmapFont::findGlyph(const char32_t codePoint)
{
    std::size_t first = 0U;
    std::size_t last = sizeof(glyphs) / sizeof(glyphs[0]);
    while (first < last)
    {
        const std::size_t middle = first + (last - first) / 2U;
        if (glyphs[middle].codePoint < codePoint)
            first = middle + 1U;
        else
            last = middle;
    }
    return first < sizeof(glyphs) / sizeof(glyphs[0])
        && glyphs[first].codePoint == codePoint ? &glyphs[first] : nullptr;
}

const uint8_t* BitmapFont::getBitmap(const BitmapGlyph& glyph)
{
    return bitmaps + glyph.bitmapOffset;
}
